export const messages: Record<Locale, Record<MessageKey, string>> = { he, en }

export function translate(
  locale: Locale,
  key: MessageKey,
  params: Record<string, string | number> = {},
): string {
  let value = messages[locale]?.[key] ?? messages.he[key] ?? key
  for (const [name, replacement] of Object.entries(params)) {
    value = value.replaceAll(`{${name}}`, String(replacement))
  }
  return value
}
